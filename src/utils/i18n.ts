    cejas: { pt: 'Sobrancelhas', es: 'Cejas', en: 'Brows' },
    uñas: { pt: 'Unhas / Nails', es: 'Uñas', en: 'Nails' },
    cabello: { pt: 'Cabelo', es: 'Cabello', en: 'Hair' },
    facial: { pt: 'Facial / Skincare', es: 'Facial', en: 'Facial' },
    maquillaje: { pt: 'Maquiagem', es: 'Maquillaje', en: 'Makeup' },
    depilacion: { pt: 'Depilação', es: 'Depilación', en: 'Waxing' },
    labios: { pt: 'Lábios / Micropigmentação', es: 'Labios / Micropigmentación', en: 'Lips' },
    outro: { pt: 'Outros', es: 'Otros', en: 'Other' }
