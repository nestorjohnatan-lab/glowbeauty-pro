export const CURRENCY_SYMBOLS: Record<CurrencyCode, string> = {
  BRL: 'R$',
  MXN: '$',
  COP: '$',
  ARS: '$',
  CLP: '$',
  PEN: 'S/',
  USD: '$',
  EUR: '€'
};

export function formatPrice(amount: number, currency: CurrencyCode = 'BRL', lang: string = 'pt'): string {
  if (currency === 'BRL') {
    return `R$ ${amount.toLocaleString('pt-BR', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
  }
  if (currency === 'EUR') {
    return `${amount.toLocaleString(lang === 'pt' ? 'pt-PT' : 'es-ES', { minimumFractionDigits: 2 })} €`;
  }
  if (currency === 'USD') {
    return `$${amount.toLocaleString('en-US', { minimumFractionDigits: 2 })}`;
  }
  const symbol = CURRENCY_SYMBOLS[currency] || '$';
  return `${symbol} ${amount.toLocaleString('es-LA', { minimumFractionDigits: 0 })} ${currency}`;
}

